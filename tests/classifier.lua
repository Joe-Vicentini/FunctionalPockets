local FP = FunctionalPockets
local function check(name, location, expected, reduction, tags, id, native)
    local actual = FP.classify(id or "Base." .. name, name, location, tags, true, native)
    if expected == nil then assert(actual == nil, name); return end
    assert(actual and actual.capacity == expected and actual.reduction == reduction, name)
end
