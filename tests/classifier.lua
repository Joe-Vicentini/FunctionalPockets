-- Damage profile regression cases (pure classifier, no game required).
local function damage(profile, holes, expected, damaged)
    local capacity, count = FP.capacityAfterHoles(profile, function(region) return holes[region] == true end)
    assert(capacity == expected and count == damaged, "unexpected damaged capacity")
end
local function trousers(name)
    return FP.classify("Base." .. name, name, "base:pants", {}, true, false)
end
local plain = trousers("Trousers")
local cargo = trousers("CargoPants")
local heavy = trousers("HeavyCargoPants")
assert(plain.pocketCount == 4 and cargo.pocketCount == 6 and heavy.pocketCount == 8)
damage(plain, {Head = true}, 2, 0)
damage(plain, {UpperLeg_L = true, UpperLeg_R = true}, 1, 2)
damage(plain, {Torso_Lower = true, Groin = true, UpperLeg_L = true, UpperLeg_R = true}, 0, 4)
damage(cargo, {LowerLeg_L = true, LowerLeg_R = true}, 3, 2)
damage(heavy, {LowerLeg_L = true, LowerLeg_R = true}, 3, 2)
damage(cargo, {}, 4, 0)
damage({capacity = 8, pocketCount = 4, pocketRegions = {"Groin", "Groin", "UpperLeg_L"}}, {Groin = true}, 6, 1)
damage({capacity = 8, pocketCount = 6, pocketRegions = {"Groin"}}, {Groin = true}, 7, 1)
damage({capacity = 8, pocketCount = 8, pocketRegions = {"Groin"}}, {Groin = true}, 7, 1)
damage({capacity = 0.5, pocketCount = 1, pocketRegions = {"Torso_Upper"}}, {Torso_Upper = true}, 0, 1)
print("Pocket damage assertions passed")

-- Public API registration regression cases.
local API = FP.API
API.registerProfile("Test.Utility", {capacity = 4, reduction = 40, maxItemSize = 0.8,
    pocketCount = 6, pocketRegions = {"Groin", "LowerLeg_L"}})
API.registerItem("Test.Custom", "Test.Utility")
check("Pocketless", "base:hat", 4, 40, {"nopockets"}, "Test.Custom")
check("Pocketless", "base:hat", nil, nil, nil, "Test.Custom", true)
local custom = FP.classify("Test.Custom", "Pocketless", "base:hat", {}, true, false)
assert(custom.maxItemSize == 0.8 and custom.pocketCount == 6 and custom.pocketRegions[2] == "LowerLeg_L")
API.overrideStats("Test.Custom", nil, 0)
check("Pocketless", "base:hat", 4, 0, nil, "Test.Custom")
API.excludeItem("Test.Custom")
check("Pants", "base:pants", nil, nil, nil, "Test.Custom")
API.overrideStats("Test.Unknown", 9, 50)
check("Unknown", "base:hat", nil, nil, nil, "Test.Unknown")
API.registerInclusionKeyword("utility-smock", "Test.Utility")
check("UtilitySmockShirt", "base:shirt", 4, 40)
