check("UtilitySmockSealedSeams", "base:shirt", nil)
API.registerBodyLocation("test:utility_slot", "Test.Utility")
check("Unknown", "test:utility_slot", 4, 40)
API.registerBulkyKeyword("long-tool")
assert(FP.isBulky("LongTool"))
assert(not pcall(API.registerInclusionKeyword, "", "Test.Utility"))
assert(not pcall(API.overrideStats, "Test.Custom", -1, 50))
